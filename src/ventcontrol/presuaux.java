    private void montoKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_montoKeyPressed
        if(evt.getKeyCode() == KeyEvent.VK_ENTER){
            if(cod.getText().length()!=0){
                DecimalFormat formateador = new DecimalFormat("###,###");
                Integer aux1=0, aux3=0;
                String aux, aux2;
                try {
                    aux = monto.getText();
                    Number c = formateador.parse(aux);
                    aux1=c.intValue();
                    aux2 = costo.getText();
                    Number x = formateador.parse(aux2);
                    aux3=x.intValue();
                } catch (ParseException ex) {
                    java.util.logging.Logger.getLogger(vuelto.class.getName()).log(Level.SEVERE, null, ex);
                } 
                if(aux1>0 && aux3>0){
                    descrippro = this.cod.getText();
                    //preciopro = this.monto.getText();
                    Integer totalaux1 = 0;
                    try{
                        Number num = formateador.parse(this.monto.getText());
                        totalaux1 = num.intValue();
                        }catch (ParseException e){
                    }
                    idcosto=aux3;
                    preciopro = totalaux1.toString();
                    this.dispose();
                    
                    }else{
                        JOptionPane.showMessageDialog(null, "Debe ingresar un precio costo y venta.");
                        monto.requestFocus();
                        monto.selectAll();
                    }
            }else{
                JOptionPane.showMessageDialog(null, "Tienes que agregar una descripcion.");
                cod.requestFocus();
            }
        }
    }//GEN-LAST:event_montoKeyPressed

