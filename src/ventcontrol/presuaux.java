    private void guardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_guardarActionPerformed
        if(cod.getText().length()!=0){
                DecimalFormat formateador = new DecimalFormat("###,###");
                Integer aux1=0;
                String aux, auxx;
                
                try {
                    aux = monto.getText();
                    Number c = formateador.parse(aux);
                    aux1=c.intValue();
                    auxx = costo.getText();
                    Number x = formateador.parse(auxx);
                    idcosto=x.intValue();
                    tipoiva=comboiva.getSelectedItem().toString();
                } catch (ParseException ex) {
                    java.util.logging.Logger.getLogger(vuelto.class.getName()).log(Level.SEVERE, null, ex);
                } 
                if(aux1>0){
                    if(idcosto>0){
                        if(aux1>idcosto){
                        descrippro = this.cod.getText();
                        //preciopro = this.monto.getText();
                        Integer totalaux1 = 0;
                        try{
                            Number num = formateador.parse(this.monto.getText());
                            totalaux1 = num.intValue();
                        }catch (ParseException e){
                        }
                            preciopro = totalaux1.toString();
                            this.dispose();
                        }else{
                            JOptionPane.showMessageDialog(null, "El costo Debe ser inferior al precio de Venta.");
                            monto.requestFocus();
                            monto.selectAll();
                        }
                        }else{
                            JOptionPane.showMessageDialog(null, "Debe ingresar un precio de Costo.");
                            monto.requestFocus();
                            monto.selectAll();
                        }
                    }else{
                        JOptionPane.showMessageDialog(null, "Debe ingresar un precio Unitario.");
                        monto.requestFocus();
                        monto.selectAll();
                    }
            }else{
                JOptionPane.showMessageDialog(null, "Tienes que agregar una descripcion.");
                cod.requestFocus();
            }        
    }//GEN-LAST:event_guardarActionPerformed

