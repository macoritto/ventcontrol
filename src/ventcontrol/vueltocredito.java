    private void montoKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_montoKeyReleased
        DecimalFormat formateador = new DecimalFormat("###,###");
        String aux;        
        Integer monto1, monto2, monto3=0, monto4=0;
        try {
            aux = monto.getText();
            Number c = formateador.parse(aux);
            monto4 = c.intValue();
            monto.setText(formateador.format(monto4));
            Number a = formateador.parse(cod.getText());
            monto1 = a.intValue();
            Number b = formateador.parse(monto.getText());
            monto2 = b.intValue();
            if(monto1>monto2){
                monto3 = monto1 - monto2;
                vuelto.setText(formateador.format(monto3));
            }else{
                JOptionPane.showMessageDialog(null, "El pago sobrepasa la deuda.");
                monto.setText("0");
                monto.selectAll();
                vuelto.setText(cod.getText());
            }
            
        } catch (ParseException ex) {
            java.util.logging.Logger.getLogger(vueltocredito.class.getName()).log(Level.SEVERE, null, ex);
        }                                
        
    }//GEN-LAST:event_montoKeyReleased

    private void montoKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_montoKeyPressed
        Integer aux1=0, aux2=0, aux3=0;
        DecimalFormat formateador = new DecimalFormat("###,###");
        if(evt.getKeyCode() == KeyEvent.VK_ENTER){
            if(calendar.getDate()!=null){
                if(monto.getText().length()==0){
                    monto.setText("0");
                    vuelto.setText(cod.getText());
                }
                try{
                    Number num = formateador.parse(cod.getText());
                    aux1=num.intValue();
                    montototal=aux1;
                    Number num1 = formateador.parse(monto.getText());
                    aux2=num1.intValue();
                    montopago=aux2;
                    Number num2 = formateador.parse(vuelto.getText());
                    aux3=num2.intValue();
                    montosaldo=aux3;
                    myDate=calendar.getDate();
                    this.dispose();
                }catch (ParseException e){
                }
                //this.dispose();
                this.band1=1;            
            }else{
                JOptionPane.showMessageDialog(null, "Debe ingresar la fecha de Vencimiento.");
            }
            
        }
    }//GEN-LAST:event_montoKeyPressed

